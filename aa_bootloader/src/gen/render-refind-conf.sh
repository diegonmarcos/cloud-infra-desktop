#!/bin/sh
# render-refind-conf.sh — boot.json → dist/boot/efi/EFI/refind/refind.conf
#
# rEFInd auto-detects most OS bootloaders by scanning EFI partitions for
# *.efi binaries. The generated config:
#   - sets UI options (timeout, default, resolution, showtools)
#   - tells rEFInd which dirs NOT to scan (orphans like EFI/GRUB, EFI/ubuntu)
#   - re-uses boot.json's grub.menu.* to emit hand-curated stanzas for the
#     entries autodetect can't reliably catch (Kali kernel symlinks, etc.)

set -eu

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(dirname "$(dirname "$SCRIPT_DIR")")"

# shellcheck source=lib/log.sh
. "$SCRIPT_DIR/lib/log.sh"
# shellcheck source=lib/json.sh
. "$SCRIPT_DIR/lib/json.sh"

BOOT_JSON="$ROOT_DIR/src/boot.json"
NIX_PROFILES="${NIX_PROFILES:-/nix/var/nix/profiles}"
OUT_DIR="$ROOT_DIR/dist/boot/efi/EFI/refind"
OUT="$OUT_DIR/refind.conf"

mkdir -p "$OUT_DIR"
log "Rendering refind.conf"

TIMEOUT=$(jq -r '.refind.ui.timeout // 5' "$BOOT_JSON")
DEFAULT=$(jq -r '.refind.ui.default_selection // "NixOS"' "$BOOT_JSON")
RESOLUTION=$(jq -r '.refind.ui.resolution // "max"' "$BOOT_JSON")
SHOWTOOLS=$(jq -r '.refind.ui.showtools | join(",")' "$BOOT_JSON")
SCANFOR=$(jq -r '.refind.scan.scanfor | join(",")' "$BOOT_JSON")
DONT_SCAN_DIRS=$(jq -r '.refind.scan.dont_scan_dirs | join(",")' "$BOOT_JSON")
USE_GRUB_MENU=$(jq -r '.refind.manual_stanzas.use_grub_menu // false' "$BOOT_JSON")

# nix_store/<HASH>-<NAME>/<file>  →  <HASH>-<NAME>-<file> (matches /boot/kernels)
nix_to_boot_name() {
    target="$1"; name=${target#/nix/store/}
    echo "${name%%/*}-${name##*/}"
}

# Stanza for a NixOS generation (default + specialisations)
emit_nixos_stanzas() {
    [ -d "$NIX_PROFILES" ] || return 0

    sys=$(readlink -f "$NIX_PROFILES/system" 2>/dev/null) || return 0
    [ -d "$sys" ] || return 0

    kernel=$(readlink "$sys/kernel" 2>/dev/null) || return 0
    initrd=$(readlink "$sys/initrd" 2>/dev/null) || return 0
    params=$(cat "$sys/kernel-params" 2>/dev/null || echo "")
    init="$sys/init"

    kboot=$(nix_to_boot_name "$kernel")
    iboot=$(nix_to_boot_name "$initrd")

    cat <<EOF

# ─── NixOS — current generation ───
menuentry "NixOS" {
    icon /EFI/refind/icons/os_nixos.png
    volume "boot"
    loader /kernels/$kboot
    initrd /kernels/$iboot
    options "init=$init $params"
}

EOF

    if [ -d "$sys/specialisation" ]; then
        for spec in "$sys/specialisation"/*; do
            [ -d "$spec" ] || continue
            name=$(basename "$spec")
            sk=$(readlink "$spec/kernel" 2>/dev/null) || continue
            si=$(readlink "$spec/initrd" 2>/dev/null) || continue
            sp=$(cat "$spec/kernel-params" 2>/dev/null || echo "")
            sinit="$spec/init"
            skboot=$(nix_to_boot_name "$sk")
            siboot=$(nix_to_boot_name "$si")
            cat <<EOF
menuentry "NixOS - $name" {
    icon /EFI/refind/icons/os_nixos.png
    volume "boot"
    loader /kernels/$skboot
    initrd /kernels/$siboot
    options "init=$sinit $sp"
}

EOF
        done
    fi
}

# Stanza for arch / kali (Linux on a separate ext4 partition)
# Reads from boot.json's grub.menu.<key> for kernel/initrd/options
emit_linux_stanza() {
    key="$1"
    enabled=$(jq -r ".grub.menu.$key.enabled // false" "$BOOT_JSON")
    [ "$enabled" = "true" ] || return 0

    label=$(jq -r ".grub.menu.$key.label" "$BOOT_JSON")
    uuid=$(jq -r ".grub.menu.$key.root_uuid" "$BOOT_JSON")
    kernel=$(jq -r ".grub.menu.$key.kernel" "$BOOT_JSON")
    initrd=$(jq -r ".grub.menu.$key.initrd" "$BOOT_JSON")
    opts=$(jq -r ".grub.menu.$key.options" "$BOOT_JSON")

    cat <<EOF
menuentry "$label" {
    icon /EFI/refind/icons/os_$key.png
    volume "$uuid"
    loader $kernel
    initrd $initrd
    options "root=UUID=$uuid $opts"
}

EOF
}

# Windows is autodetected via EFI/Microsoft/Boot/bootmgfw.efi — no stanza needed

{
    cat <<EOF
# AUTO-GENERATED by aa_bootloader/src/gen/render-refind-conf.sh
# DO NOT EDIT — regenerated from src/boot.json
# Generated: $(date '+%Y-%m-%d %H:%M:%S UTC%z')

timeout         $TIMEOUT
default_selection "$DEFAULT"
resolution      $RESOLUTION
use_graphics_for linux,windows
showtools       $SHOWTOOLS
scanfor         $SCANFOR

# Skip orphaned directories (left over from prior bootloaders)
EOF

    # rEFInd's dont_scan_dirs takes a CSV. Each volume optionally prefixed.
    if [ -n "$DONT_SCAN_DIRS" ]; then
        echo "dont_scan_dirs   $DONT_SCAN_DIRS"
    fi

    cat <<EOF

# ═══════════════════════════════════════════════════════════════════════════
# Manual stanzas (override / supplement autodetect)
# ═══════════════════════════════════════════════════════════════════════════
EOF

    if [ "$USE_GRUB_MENU" = "true" ]; then
        emit_nixos_stanzas
        emit_linux_stanza arch
        emit_linux_stanza kali
    fi

    cat <<EOF
# Windows: autodetected via /EFI/Microsoft/Boot/bootmgfw.efi
# GRUB:    autodetected via /EFI/NixOS-boot-efi/grubx64.efi (kept as fallback)
EOF

} > "$OUT"

log "Wrote: $OUT  ($(wc -l < "$OUT") lines)"
