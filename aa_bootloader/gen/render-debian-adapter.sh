#!/bin/sh
# render-debian-adapter.sh — Phase 2 STUB
# Will emit /etc fragments for Kali/Kubuntu (crypttab, /etc/default/grub,
# initramfs-tools conf.d). Not implemented in Phase 1.

set -eu

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(dirname "$SCRIPT_DIR")"

# shellcheck source=lib/log.sh
. "$SCRIPT_DIR/lib/log.sh"

DIST="$ROOT_DIR/dist/adapters/debian"
mkdir -p "$DIST/etc/default" "$DIST/etc/initramfs-tools/conf.d"

cat > "$DIST/PHASE_2_STUB.txt" <<'EOF'
This directory is a Phase 2 stub.

When Phase 2 lands, it will contain:
  - etc/crypttab.aa-fragment
  - etc/default/grub.aa
  - etc/initramfs-tools/conf.d/aa_bootloader.conf

Generated by gen/render-debian-adapter.sh from src/boot.json.
EOF

warn "render-debian-adapter.sh is a Phase 2 stub — no real adapter content yet"
