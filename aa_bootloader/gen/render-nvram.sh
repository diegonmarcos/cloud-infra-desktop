#!/bin/sh
# render-nvram.sh — emit dist/nvram/apply.sh with idempotent efibootmgr commands
# Reads src/boot.json's uefi.nvram block.
# The output script:
#   - Ensures every entry in uefi.nvram.entries[] exists (creates if missing)
#   - Removes entries listed in uefi.nvram.remove_stale[] (by Name match)
#   - Sets BootOrder so default=true entries lead

set -eu

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(dirname "$SCRIPT_DIR")"

# shellcheck source=lib/log.sh
. "$SCRIPT_DIR/lib/log.sh"
# shellcheck source=lib/json.sh
. "$SCRIPT_DIR/lib/json.sh"

BOOT_JSON="$ROOT_DIR/src/boot.json"
DIST="$ROOT_DIR/dist/nvram"
OUT="$DIST/apply.sh"

mkdir -p "$DIST"

MANAGE=$(jq -r '.uefi.nvram.manage // false' "$BOOT_JSON")
ESP_UUID=$(jq -r '.uefi.esp.uuid' "$BOOT_JSON")
# Find which disk has the ESP — needed for `efibootmgr --create -d ... -p ...`.
# Defaults match Surface Pro 8: /dev/nvme0n1, partition 1 = ESP.
DISK="${NVRAM_DISK:-/dev/nvme0n1}"
PART="${NVRAM_ESP_PART:-1}"

{
    cat <<EOF
#!/bin/sh
# AUTO-GENERATED by aa_bootloader/gen/render-nvram.sh
# Idempotent efibootmgr script. Re-run safe.
# Generated: $(date '+%Y-%m-%d %H:%M:%S')

set -eu

if [ "\$(id -u)" -ne 0 ]; then
    echo "[nvram/apply.sh] Must run as root" >&2
    exit 1
fi

if [ ! -d /sys/firmware/efi ]; then
    echo "[nvram/apply.sh] Not booted via UEFI — skipping NVRAM" >&2
    exit 0
fi

EOF

    if [ "$MANAGE" != "true" ]; then
        cat <<'EOF'
echo "[nvram/apply.sh] uefi.nvram.manage=false in boot.json — no-op."
exit 0
EOF
    else
        cat <<EOF
DISK="$DISK"
PART="$PART"

# Snapshot current state for diff/log
echo "[nvram] before:"
efibootmgr | head -30

# Helper: find existing entry by name (returns BootXXXX hex or empty)
find_entry() {
    name="\$1"
    efibootmgr | awk -v n="\$name" '\$0 ~ "Boot[0-9A-Fa-f]+\\\\* "n"\$" || \$0 ~ "Boot[0-9A-Fa-f]+\\\\* "n" " { sub("Boot",""); sub("\\\\*.*",""); print; exit }'
}

# Remove stale entries
EOF
        jq -r '.uefi.nvram.remove_stale[]?' "$BOOT_JSON" | while read -r stale_name; do
            cat <<EOF
echo "[nvram] checking stale: $stale_name"
existing=\$(find_entry "$stale_name")
if [ -n "\$existing" ]; then
    echo "[nvram] removing Boot\$existing ($stale_name)"
    efibootmgr -B -b "\$existing" >/dev/null
fi
EOF
        done

        cat <<'EOF'

# Ensure required entries exist
EOF
        # Pass name and path via tab-separated tuples to avoid round-tripping
        # JSON-escaped backslashes through shell echo (which mangles them).
        jq -r '.uefi.nvram.entries[] | [.name, .path] | @tsv' "$BOOT_JSON" | \
        while IFS=$(printf '\t') read -r NAME EFIPATH; do
            cat <<EOF
existing=\$(find_entry "$NAME")
if [ -z "\$existing" ]; then
    echo "[nvram] creating: $NAME -> $EFIPATH"
    efibootmgr -c -d "\$DISK" -p "\$PART" -L "$NAME" -l "$EFIPATH" >/dev/null
else
    echo "[nvram] keeping Boot\$existing ($NAME)"
fi
EOF
        done

        cat <<'EOF'

echo "[nvram] after:"
efibootmgr | head -30
EOF
    fi
} > "$OUT"

chmod +x "$OUT"
log "Wrote: $OUT (manage=$MANAGE)"
